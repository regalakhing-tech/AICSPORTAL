// npm install --prefix scratch/admin-user-form-qa --no-save --package-lock=false jsdom@26
// Set NODE_PATH to scratch/admin-user-form-qa/node_modules before running this test.
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const html = execFileSync('php', [path.join(__dirname, 'admin-user-form-render-test.php'), '--fixture'], { encoding: 'utf8' });
const dom = new JSDOM(html, { runScripts: 'outside-only', url: 'http://localhost/ADMIN/phpfiles/user-management.php' });
const { window } = dom;
window.TextEncoder = TextEncoder;
// DOM tests have no layout engine. Limit the focus list to enabled, non-hidden controls.
window.HTMLElement.prototype.getClientRects = function () { return this.closest('[hidden]') ? [] : [{}]; };
window.eval(fs.readFileSync(path.join(__dirname, '../ADMIN/jsfiles/admin-user-form.js'), 'utf8'));
window.eval(fs.readFileSync(path.join(__dirname, '../ADMIN/jsfiles/admin-pages.js'), 'utf8'));
const doc = window.document;
const form = doc.getElementById('create-user-form');
const shell = doc.getElementById('modal-create-user');
const trigger = doc.querySelector('[data-modal-open]');
const input = (name, value, event = 'input') => {
  const field = form.elements.namedItem(name);
  field.value = value;
  field.dispatchEvent(new window.Event(event, { bubbles: true }));
  return field;
};
const submit = () => { const event = new window.Event('submit', { bubbles: true, cancelable: true }); form.dispatchEvent(event); return event; };
trigger.focus(); trigger.click();
assert.ok(shell.classList.contains('open'));
assert.equal(doc.activeElement.id, 'create-user-errors', 'A reopened failed form should focus its errors.');
assert.equal(input('email', 'new@example.test').hasAttribute('aria-invalid'), false, 'Editing a field with a server error should revalidate it.');
assert.equal(submit().defaultPrevented, true, 'Invalid input must prevent submission.');
assert.equal(form.getAttribute('aria-busy'), null);
assert.equal(doc.activeElement.id, 'create-user-errors');
input('first_name', 'María'); input('last_name', 'Dela Cruz');
input('role_code', 'pswdo', 'change');
assert.equal(form.elements.namedItem('position_title').disabled, false);
assert.equal(form.elements.namedItem('address').disabled, true);
input('role_code', 'applicat', 'change');
assert.equal(form.elements.namedItem('position_title').disabled, true);
assert.equal(form.elements.namedItem('address').disabled, false);
input('contact_number', '+63 917 123 4567');
input('password', 'TestUser!42'); input('confirm_password', 'wrong', 'blur');
assert.equal(form.elements.namedItem('confirm_password').getAttribute('aria-invalid'), 'true');
assert.equal(doc.querySelectorAll('[data-password-rule].met').length, 4);
input('confirm_password', 'TestUser!42');
assert.equal(form.elements.namedItem('confirm_password').hasAttribute('aria-invalid'), false);
const toggle = form.querySelector('[data-password-toggle]');
toggle.click(); assert.equal(form.elements.namedItem('password').type, 'text');
toggle.click(); assert.equal(form.elements.namedItem('password').type, 'password');
const last = doc.getElementById('create-user-submit');
last.focus();
const tab = new window.KeyboardEvent('keydown', { key: 'Tab', bubbles: true, cancelable: true });
last.dispatchEvent(tab);
assert.ok(tab.defaultPrevented);
assert.equal(doc.activeElement, shell.querySelector('button'), 'Tab should stay in the dialog.');
const reverse = new window.KeyboardEvent('keydown', { key: 'Tab', shiftKey: true, bubbles: true, cancelable: true });
doc.activeElement.dispatchEvent(reverse);
assert.equal(doc.activeElement, last);
doc.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
assert.equal(shell.classList.contains('open'), false);
assert.equal(doc.activeElement, trigger);
assert.equal(form.elements.namedItem('password').value, '', 'Closing the form should clear secrets.');
trigger.click(); input('password', 'TestUser!42'); input('confirm_password', 'TestUser!42');
assert.equal(submit().defaultPrevented, false, 'Valid input should continue to the server.');
assert.equal(last.disabled, true);
assert.equal(form.getAttribute('aria-busy'), 'true');
window.close();
const reopened = new JSDOM(html.replace('id="user-management-root"', 'id="user-management-root" data-auto-open-modal="create"'), { runScripts: 'outside-only', url: 'http://localhost/ADMIN/phpfiles/user-management.php' });
reopened.window.TextEncoder = TextEncoder;
reopened.window.eval(fs.readFileSync(path.join(__dirname, '../ADMIN/jsfiles/admin-user-form.js'), 'utf8'));
reopened.window.eval(fs.readFileSync(path.join(__dirname, '../ADMIN/jsfiles/admin-pages.js'), 'utf8'));
const reopenedDoc = reopened.window.document;
assert.equal(reopenedDoc.activeElement.id, 'create-user-errors');
reopenedDoc.querySelector('#modal-create-user button[data-modal-close]').click();
assert.equal(reopenedDoc.activeElement, reopenedDoc.querySelector('[data-modal-open]'), 'Closing an automatically reopened form must return focus to Add User.');
reopened.window.close();
console.log('Admin Add User DOM interaction checks passed.');
